-- 대회 전용 문제. Supabase 대시보드의 SQL Editor에서 한 번 실행한다. 다시 실행해도 된다.
--
-- 대회 개설 화면에서 그 대회만을 위한 문제를 만들 수 있다. 그런 문제는
--   - 만들 때는 공개 번호와 겹치지 않는 임시 번호(10억부터)를 받고 문제 목록에 보이지 않는다.
--   - 대회가 시작하면 대회 화면에서만 풀 수 있다(문제 목록과 연습 제출에는 나오지 않는다).
--   - 대회가 끝나고 2분쯤 지나면 백엔드가 publish_contest_problems()를 불러, 그때 있는 마지막
--     문제 번호 다음 번호로 옮겨 공개한다. 여러 문제면 대회의 A, B, C 순서대로 번호를 받는다.
--     문제를 가리키는 표(test_cases, contest_problems, problem_tags, submissions, contest_drafts)도
--     함께 옮기므로 제출 기록과 태그가 그대로 따라간다.
--
-- 실행하고 나면:
--   problems.contest_only          대회 전용인지. 공개되면 false가 된다.
--   reserve_contest_problem_id()   관리자 화면이 대회 전용 문제의 임시 번호를 받는다(관리자만).
--   problem_is_released()          대회 전용 문제는 시작한 대회에 들어 있을 때만 읽힌다.
--   publish_contest_problems()     끝난 대회의 대회 전용 문제를 공개한다(백엔드만 부른다).
--   문제를 가리키는 외래 키         번호를 옮기는 동안 잠깐 어긋날 수 있게 검사를 커밋 때로 미룰 수
--                                  있게(deferrable) 바꾼다. 평소 동작은 같다.
--
-- 백엔드보다 먼저 실행한다. 전체가 한 트랜잭션이라 중간에 실패하면 아무것도 바뀌지 않는다.
-- 마지막에 점검 결과가 나온다.

begin;

-- 1. 대회 전용 표시
alter table public.problems add column if not exists contest_only boolean not null default false;

-- 관리자 화면이 받은 임시 번호를 id에 직접 넣으므로, id가 "늘 자동(always)"이면 "기본 자동"으로 바꾼다.
do $$
begin
  if exists (
    select 1 from pg_attribute
    where attrelid = 'public.problems'::regclass and attname = 'id' and attidentity = 'a'
  ) then
    alter table public.problems alter column id set generated by default;
  end if;
end $$;

-- 2. 임시 번호. 공개 번호의 시퀀스를 쓰지 않으므로 공개 문제 번호에 빈칸이 생기지 않는다.
create sequence if not exists public.contest_problem_ids start with 1000000001;
revoke all on sequence public.contest_problem_ids from public, anon, authenticated;

create or replace function public.reserve_contest_problem_id()
returns bigint
language plpgsql volatile security definer set search_path = ''
as $$
begin
  if not public.current_user_is_admin() then
    raise exception '관리자만 대회 전용 문제를 만들 수 있습니다.' using errcode = '42501';
  end if;
  return nextval('public.contest_problem_ids');
end
$$;

revoke all on function public.reserve_contest_problem_id() from public;
grant execute on function public.reserve_contest_problem_id() to authenticated, service_role;

-- 3. 공개 여부. 시작 전 대회의 문제는 숨기고, 대회 전용 문제는 시작한 대회에 들어 있어야 보인다
--    (대회 중에는 대회 화면이 읽어야 하고, 대회에 넣기 전의 문제는 관리자만 본다).
--    문제 목록에서 대회 전용 문제를 빼는 것은 화면이 contest_only로 거른다.
create or replace function public.problem_is_released(target bigint)
returns boolean
language sql stable security definer set search_path = ''
as $$
  select not exists (
      select 1
      from public.contest_problems cp
      join public.contests c on c.id = cp.contest_id
      where cp.problem_id = target and c.start_time > now()
    )
    and (
      not coalesce((select p.contest_only from public.problems p where p.id = target), false)
      or exists (
        select 1
        from public.contest_problems cp
        join public.contests c on c.id = cp.contest_id
        where cp.problem_id = target and c.start_time <= now()
      )
    )
$$;

-- 4. 번호를 옮기는 동안 외래 키 검사를 커밋 때로 미룰 수 있게 한다. 평소에는 지금처럼 바로 검사한다.
do $$
declare
  fk record;
begin
  for fk in
    select con.conrelid::regclass as tbl, con.conname
    from pg_constraint con
    where con.contype = 'f' and con.confrelid = 'public.problems'::regclass and not con.condeferrable
  loop
    execute format('alter table %s alter constraint %I deferrable initially immediate', fk.tbl, fk.conname);
  end loop;
end $$;

-- 5. 끝난 대회의 대회 전용 문제를 공개한다. 옮긴 문제 수를 돌려준다.
create or replace function public.publish_contest_problems()
returns integer
language plpgsql volatile security definer set search_path = ''
as $$
declare
  id_sequence text := pg_get_serial_sequence('public.problems', 'id');
  unknown text;
  item record;
  next_id bigint;
  moved integer := 0;
begin
  -- 문제 번호를 가리키는 표가 아래에서 옮기는 것 말고도 있으면, 그 표의 번호가 어긋나지 않게 멈춘다.
  select string_agg(distinct con.conrelid::regclass::text, ', ') into unknown
  from pg_constraint con
  where con.contype = 'f'
    and con.confrelid = 'public.problems'::regclass
    and con.conrelid not in (
      'public.test_cases'::regclass, 'public.contest_problems'::regclass, 'public.problem_tags'::regclass,
      'public.submissions'::regclass, 'public.contest_drafts'::regclass
    );
  if unknown is not null then
    raise exception '문제 번호를 가리키는 표 %도 옮겨야 합니다. publish_contest_problems()를 고친 뒤 다시 실행하세요.', unknown;
  end if;

  -- 같은 때에 관리자가 문제를 등록해 번호가 겹치지 않게 한다.
  lock table public.problems in share row exclusive mode;
  set constraints all deferred;

  for item in
    select p.id as old_id
    from public.problems p
    join public.contest_problems cp on cp.problem_id = p.id
    join public.contests c on c.id = cp.contest_id
    where p.contest_only
    group by p.id
    -- 들어 있는 대회가 모두 2분 이상 전에 끝났고, 마지막 제출들의 채점도 끝났을 때.
    -- (채점기가 멈춰 10분 넘게 남은 제출은 기다리지 않는다.)
    having max(c.end_time) <= now() - interval '2 minutes'
      and not exists (
        select 1 from public.submissions s
        where s.problem_id = p.id
          and s.status in ('Pending', 'Running')
          and s.created_at > now() - interval '10 minutes'
      )
    order by max(c.end_time), min(cp."order"), p.id
  loop
    select coalesce(max(id), 0) + 1 into next_id from public.problems where not contest_only;
    update public.problems set id = next_id, contest_only = false where id = item.old_id;
    update public.test_cases set problem_id = next_id where problem_id = item.old_id;
    update public.contest_problems set problem_id = next_id where problem_id = item.old_id;
    update public.problem_tags set problem_id = next_id where problem_id = item.old_id;
    update public.submissions set problem_id = next_id where problem_id = item.old_id;
    update public.contest_drafts set problem_id = next_id where problem_id = item.old_id;
    moved := moved + 1;
  end loop;

  -- 다음에 등록하는 문제가 그다음 번호를 받게 한다.
  if moved > 0 and id_sequence is not null then
    perform setval(id_sequence, (select max(id) from public.problems where not contest_only));
  end if;
  return moved;
end
$$;

revoke all on function public.publish_contest_problems() from public;
grant execute on function public.publish_contest_problems() to service_role;

-- 6. 점검
select item, ok, detail
from (
  select 1 as n, '칸 추가: problems.contest_only' as item,
         exists (select 1 from information_schema.columns
                 where table_schema = 'public' and table_name = 'problems' and column_name = 'contest_only') as ok,
         '' as detail
  union all
  select 2, '문제 번호 자동 매기기', a.attidentity <> 'a',
         case a.attidentity when 'd' then 'identity (by default)' when 'a' then 'identity (always)'
              else coalesce(pg_get_expr(d.adbin, d.adrelid), '없음') end
  from pg_attribute a
  left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
  where a.attrelid = 'public.problems'::regclass and a.attname = 'id'
  union all
  select 3, '문제 번호를 가리키는 외래 키: ' || con.conrelid::regclass::text,
         con.condeferrable and con.conrelid in (
           'public.test_cases'::regclass, 'public.contest_problems'::regclass, 'public.problem_tags'::regclass,
           'public.submissions'::regclass, 'public.contest_drafts'::regclass),
         con.conname
  from pg_constraint con
  where con.contype = 'f' and con.confrelid = 'public.problems'::regclass
  union all
  select 4, '대회 전용 문제(공개 전)', true, count(*)::text || '개'
  from public.problems where contest_only
) checks
order by n, item;

commit;
